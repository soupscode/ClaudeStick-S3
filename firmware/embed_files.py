"""PlatformIO pre-build step: embed the hook + installer so the Stick can serve them.

Also runnable by hand: python3 embed_files.py
"""
import hashlib
import os

try:
    Import("env")  # noqa: F821  (provided by PlatformIO/SCons)
    ROOT = env["PROJECT_DIR"]  # noqa: F821
except NameError:
    ROOT = os.path.dirname(os.path.abspath(__file__))

REPO = os.path.dirname(ROOT)
FILES = {
    "EMBED_INSTALL_PY": "install.py",
    "EMBED_HOOK_PY": "hooks/claudestick_hook.py",
    "EMBED_SETUP_HTML": "firmware/setup_page.html",
}
DELIM = "CSEMBED"

out = ["// Generated by embed_files.py from the repo's install.py and hooks/. Do not edit.", "#pragma once", ""]
for name, rel in FILES.items():
    with open(os.path.join(REPO, rel), encoding="utf-8") as f:
        body = f.read()
    if name == "EMBED_HOOK_PY":  # lets installed hooks notice they're out of date and refresh themselves
        out.append(f'#define EMBED_HOOK_SHA "{hashlib.sha256(body.encode("utf-8")).hexdigest()}"')
    assert f"){DELIM}\"" not in body
    out.append(f'static const char {name}[] PROGMEM = R"{DELIM}({body}){DELIM}";')
    out.append("")
# Build info: the OTA update source (CI sets CS_UPDATE_URL to the GitHub Pages URL).
url = os.environ.get("CS_UPDATE_URL", "").strip()
info = ["// Generated by embed_files.py. Do not edit.", "#pragma once"]
if url:
    if not url.endswith("/"):
        url += "/"
    info.append(f'#define CS_UPDATE_URL "{url}"')
info_dst = os.path.join(ROOT, "src", "build_info.h")
info_new = "\n".join(info) + "\n"
if not os.path.exists(info_dst) or open(info_dst, encoding="utf-8").read() != info_new:
    with open(info_dst, "w", encoding="utf-8") as f:
        f.write(info_new)

dst = os.path.join(ROOT, "src", "embedded_files.h")
new = "\n".join(out)
if not os.path.exists(dst) or open(dst, encoding="utf-8").read() != new:
    with open(dst, "w", encoding="utf-8") as f:
        f.write(new)
    print("embed_files: wrote", dst)
