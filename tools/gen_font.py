def column_bytes(rows):
    rows = list(rows) + ['.....'] * (8 - len(rows))
    assert len(rows) == 8, rows
    cols = []
    for x in range(5):
        b = 0
        for y, row in enumerate(rows):
            assert len(row) == 5 and set(row) <= set('.#'), (row,)
            if row[x] == '#':
                b |= 1 << y
        cols.append(b)
    return cols


def main():
    for c in range(32, 127):
        assert chr(c) in G, f'missing glyph {chr(c)!r}'
    data = []
    for c in range(256):
        data += column_bytes(G[chr(c)]) if chr(c) in G else [0] * 5
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'firmware', 'src', 'termfont.h')
    with open(out, 'w') as f:
        f.write('// Generated by tools/gen_font.py. Do not edit; change the art there.\n#pragma once\n#include <stdint.h>\n')
        f.write('static const uint8_t termfont_info[3] = { 0, 255, 5 };   // first code, last code, columns per glyph\n')
        f.write('static const uint8_t termfont_data[256 * 5] = {\n')
        for i in range(0, len(data), 10):
            f.write('  ' + ', '.join('0x%02X' % b for b in data[i:i + 10]) + ',\n')
        f.write('};\n')
    print('wrote', os.path.normpath(out), len(data), 'bytes')


if __name__ == '__main__':
    main()
