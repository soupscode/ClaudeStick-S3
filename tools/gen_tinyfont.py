#!/usr/bin/env python3
"""Generate firmware/src/tinyfont.h from the 3x5 "Tom Thumb" font that ships with M5GFX.

Usage: gen_tinyfont.py [path/to/M5GFX/src/lgfx/Fonts/GFXFF/TomThumb.h]
Each glyph becomes 7 bytes (rows 0-6, 4-bit columns, bit 3 = leftmost) so the firmware can draw it
with plain rectangles. The font is BSD 3-clause; its notice is reproduced in the generated header.
"""
import os, re, sys

src = sys.argv[1] if len(sys.argv) > 1 else '/tmp/M5GFX/src/lgfx/Fonts/GFXFF/TomThumb.h'
t = open(src).read()
notice = t[t.index('/**'):t.index('*/') + 2]
bm = t[t.index('TomThumbBitmaps'):]; bm = bm[bm.index('{'):bm.index('};')]
bitmaps = [int(x, 16) for x in re.findall(r'0x[0-9A-Fa-f]{2}', re.sub(r'/\*.*?\*/', '', bm))]
gl = t[t.index('TomThumbGlyphs'):]; gl = re.sub(r'/\*.*?\*/', '', gl[gl.index('{'):gl.index('};')])
glyphs = [tuple(int(x) for x in m) for m in
          re.findall(r'\{\s*(-?\d+),\s*(-?\d+),\s*(-?\d+),\s*(-?\d+),\s*(-?\d+),\s*(-?\d+)\s*\}', gl)]
assert len(glyphs) >= 95, len(glyphs)
rows_out = []
for off, w, h, adv, xo, yo in glyphs[:95]:
    bits = bitmaps[off:off + (w * h + 7) // 8]
    rows = [0] * 7
    n = 0
    for r in range(h):
        for q in range(w):
            if bits[n >> 3] & (0x80 >> (n & 7)):
                row, col = 5 + yo + r, xo + q
                assert 0 <= row < 7 and 0 <= col < 4, (row, col)
                rows[row] |= 1 << (3 - col)
            n += 1
    rows_out.append(rows)
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'firmware', 'src', 'tinyfont.h')
with open(out, 'w') as f:
    f.write('// Generated by tools/gen_tinyfont.py from M5GFX\'s TomThumb.h. 3x5 glyphs in a 4x7 cell, ASCII 0x20-0x7E.\n')
    f.write('// The original font and its license (reproduced below) are by Brian J. Swetland, Vassilii Khachaturov,\n')
    f.write('// Dan Marks and Robey Pointer; converted to Adafruit GFX format by William Skellenger.\n/*\n')
    f.write('\n'.join(l.rstrip() for l in notice.strip('/*').strip().splitlines()) + '\n*/\n')
    f.write('#pragma once\n#include <stdint.h>\n')
    f.write('static const uint8_t tinyfont_rows[95][7] = {\n')
    for i, r in enumerate(rows_out):
        f.write('  { ' + ', '.join('0x%X' % b for b in r) + ' },   // ' + (repr(chr(0x20 + i)) if chr(0x20 + i) != '\\' else "'\\\\'") + '\n')
    f.write('};\n')
print('wrote', os.path.normpath(out))
